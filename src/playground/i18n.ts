export function tr(lang: Lang, key: string, vars?: Record<string, string | number>) {
  let s = lang === 'ru' ? key : D[key]?.[lang === 'en' ? 0 : 1] ?? key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Если текст — перевод одного из ключей на языке from, вернуть его же на языке to; иначе (пользователь поменял) оставить как есть. */
export function retr(text: string, from: Lang, to: Lang) {
  if (from === to) return text;
  for (const k in D) if (tr(from, k) === text) return tr(to, k);
  return text;
}

export const LangCtx = createContext<Lang>('en');
export const useT = () => {
  const lang = useContext(LangCtx);
  return (key: string, vars?: Record<string, string | number>) => tr(lang, key, vars);
};
